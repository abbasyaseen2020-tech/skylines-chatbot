def format_projects_for_search(property_type=None, area=None, budget_max=None):
    """بحث في المشاريع حسب المعايير"""
    results = []
    for ptype, areas in PROJECTS.items():
        if property_type and property_type not in ptype:
            continue
        for area_name, projects in areas.items():
            if area and area not in area_name:
                continue
            for p in projects:
                results.append({
                    "type": ptype,
                    "area": area_name,
                    **p
                })
    return results
